from __future__ import annotations

import csv
import json
from pathlib import Path
from time import perf_counter

from calg.solver.detector import ContactDetector
from .cases import default_cases, ValidationCase
from .metrics import compute_case_metrics, CaseMetrics


def run_cases(out_dir: str | Path, cases: list[ValidationCase] | None = None, make_plots: bool = False) -> list[CaseMetrics]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    cases = default_cases() if cases is None else cases
    metrics: list[CaseMetrics] = []
    detector_cache: dict[float, ContactDetector] = {}

    for case in cases:
        detector = detector_cache.setdefault(case.d_hat, ContactDetector(d_hat=case.d_hat, mu_min=0.20, two_sided=True))
        t0 = perf_counter()
        result = detector.detect(case.mesh_a, case.mesh_b)
        elapsed = perf_counter() - t0
        m = compute_case_metrics(case.name, case.expected_gap, result)
        metrics.append(m)
        # Write per-case details.
        detail_path = out_dir / f"{case.name}_contacts.json"
        with detail_path.open("w", encoding="utf8") as f:
            json.dump(
                {
                    "case": case.name,
                    "description": case.description,
                    "d_hat": case.d_hat,
                    "expected_gap": case.expected_gap,
                    "elapsed_s": elapsed,
                    "stats": result.stats.__dict__,
                    "contacts": result.to_rows(),
                },
                f,
                indent=2,
            )

    csv_path = out_dir / "validation_summary.csv"
    with csv_path.open("w", newline="", encoding="utf8") as f:
        writer = csv.DictWriter(f, fieldnames=list(metrics[0].to_dict().keys()))
        writer.writeheader()
        for m in metrics:
            writer.writerow(m.to_dict())

    md_path = out_dir / "validation_summary.md"
    with md_path.open("w", encoding="utf8") as f:
        f.write("# CALG validation summary\n\n")
        f.write("This file is generated by `calg.experiments.runner`. Values are not hand-entered.\n\n")
        f.write("| case | expected gap | min gap | abs error | contacts | candidates | fast path ratio |\n")
        f.write("|---|---:|---:|---:|---:|---:|---:|\n")
        for m in metrics:
            f.write(
                f"| {m.case} | {m.expected_gap} | {m.min_gap:.8g} | {m.abs_error if m.abs_error is not None else ''} | {m.contacts} | {m.candidate_pairs} | {m.fast_path_ratio:.3f} |\n"
            )

    if make_plots:
        try:
            _make_plots(metrics, out_dir)
        except Exception as e:  # plotting should not break validation
            (out_dir / "plot_warning.txt").write_text(str(e), encoding="utf8")
    return metrics


def _make_plots(metrics: list[CaseMetrics], out_dir: Path) -> None:
    import matplotlib.pyplot as plt

    names = [m.case for m in metrics]
    errors = [m.abs_error if m.abs_error is not None else 0.0 for m in metrics]
    ratios = [m.fast_path_ratio for m in metrics]

    fig = plt.figure(figsize=(8, 4))
    ax = fig.add_subplot(111)
    ax.bar(range(len(names)), errors)
    ax.set_xticks(range(len(names)))
    ax.set_xticklabels(names, rotation=35, ha="right")
    ax.set_ylabel("absolute min-gap error")
    ax.set_title("Analytic gap validation")
    fig.tight_layout()
    fig.savefig(out_dir / "gap_error.png", dpi=160)
    plt.close(fig)

    fig = plt.figure(figsize=(8, 4))
    ax = fig.add_subplot(111)
    ax.bar(range(len(names)), ratios)
    ax.set_xticks(range(len(names)))
    ax.set_xticklabels(names, rotation=35, ha="right")
    ax.set_ylabel("graph fast-path ratio")
    ax.set_ylim(0, 1.05)
    ax.set_title("Normal-cone graphability pass ratio")
    fig.tight_layout()
    fig.savefig(out_dir / "fast_path_ratio.png", dpi=160)
    plt.close(fig)
